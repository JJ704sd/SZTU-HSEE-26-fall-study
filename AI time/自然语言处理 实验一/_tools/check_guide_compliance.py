    ("实验总结与感悟", ANY, ["六、实验总结与感悟"]),
    ("思考题", ANY, ["七、思考题"]),
    # 指导书 p9 对 AI 说明的五个明文方面
    ("AI说明·工具/模型", ALL, ["工具", "模型"]),
    ("AI说明·使用目的", ALL, ["使用目的"]),
    ("AI说明·关键提问概述", ALL, ["关键提问"]),
    ("AI说明·采用内容", ALL, ["采用内容"]),
    ("AI说明·人工核验", ANY, ["人工核验", "核验"]),
    # 模板备注对 AI 说明的四个明文方面
    ("AI说明·使用环节", ALL, ["使用环节"]),
    ("AI说明·具体交互", ALL, ["具体交互"]),
