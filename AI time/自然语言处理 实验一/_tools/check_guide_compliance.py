# 封面字段（规范性 10 分明文「封面内容是否完整」）。
#
# 为什么值得单独做一道：提交格式是 PDF（评分标准：提交其他版本扣 10 分），
# **空白处在 PDF 里无法事后手写补救**。所以封面必须在生成阶段就填满，
# 这也正是"当年底稿留空、没人提醒"会一路带到交卷的原因。
#
# EXEMPT 里的是**有意留空**并已由本人确认的字段，不是漏填；理由写在代码里，
# 别为了让门禁变绿而把理由删掉——那等于把"已知例外"变成"没人知道的例外"。
COVER_FIELDS = [
    ("课程编号", ""),
    ("课程名称", ""),
    ("实验名称", ""),
    ("班　　级", ""),
    ("指导教师", ""),
    ("报 告 人", ""),
    ("学　　号", ""),
    ("合作者", ""),
    ("组号", "本人无小组编号；编造一个属于臆造，经本人 2026-10-10 确认留空"),
    ("实验地点", ""),
    ("实验时间", ""),
    ("提交时间", ""),
]

# 指导书 p9 六、思考题 的四问题干关键词
QUESTIONS = [
    "为什么不能把所有数字、英文和标点全部删除",
    'errors="ignore"',
    "NFKC",
    "隐私正则",
]

MAX_PAGES = 10


def main():
    pages = [(p.extract_text() or "") for p in pypdf.PdfReader(str(PDF)).pages]
    norm = re.sub(r"\s+", "", "\n".join(pages))
    print(f"核对文件：{PDF.name}")
    print(f"PDF 页数 = {len(pages)}\n")

    miss = []
    for name, mode, keys in CHECKS:
        hit = [k for k in keys if re.sub(r"\s+", "", k) in norm]
        need = len(keys) if mode == ALL else 1
        ok = len(hit) >= need
        if not ok:
            miss.append(name)
        print(f"  [{'OK ' if ok else '缺失'}] {name:<28}"
              f" ({mode} {len(hit)}/{len(keys)}) 命中 {hit if hit else '—'}")

    print("\n思考题四问题干（指导书 p9 原题）：")
    q_miss = []
    for i, q in enumerate(QUESTIONS, 1):
        ok = q in norm
        if not ok:
            q_miss.append(f"Q{i}")
        print(f"  Q{i}: {'OK ' if ok else '缺失'} {q}")

    # ---------------- 封面字段完整性（规范性 10 分）----------------
    # 只看**封面那一页**：find 取的是首次出现，正文里再出现同名字样不会干扰。
    # 值 = 该标签冒号之后、下一个标签冒号之前的文字；空白即视为未填。
    print("\n封面字段完整性（评分标准规范性：封面内容是否完整）：")
    cover_txt = re.sub(r"\s+", "", pages[0])
    nzl = [(lb, re.sub(r"\s+", "", lb), ex) for lb, ex in COVER_FIELDS]
    for label, nz, exempt in nzl:
        key = nz + "："
        i = cover_txt.find(key)
        if i < 0:
            val, ok = "", False
        else:
            start = i + len(key)
            ends = [cover_txt.find(n + "：", start) for _, n, _ in nzl]
            ends = [e for e in ends if e >= 0]
            val = cover_txt[start:min(ends)] if ends else cover_txt[start:start + 40]
            ok = bool(val)
        if ok:
            mark = "OK "
        elif exempt:
            mark = "豁免"
        else:
            mark = "缺失"
        note = f"  ← {exempt}" if (exempt and not ok) else ""
        print(f"  [{mark}] {label:<8} = {val or '（空）'}{note}")
        if not ok and not exempt:
            miss.append(f"封面字段「{label}」未填")

    print()
    pages_ok = len(pages) <= MAX_PAGES
    print(f"页数 = {len(pages)} （上限 {MAX_PAGES}）", "OK" if pages_ok else "超限")
    if not pages_ok:
        miss.append("总页数超过 10 页")

    print("\n=== 结论 ===")
    if miss or q_miss:
        print(f"缺失项：{miss + q_miss}")
        print("这些是指导书 p9 / 模板备注的明文要求项，不能靠人工记忆兜底。")
        return 1
    print("缺失项：无。指导书「报告必须包含」清单、思考题题干与页数上限全部满足。")
    return 0


if __name__ == "__main__":
    sys.exit(main())