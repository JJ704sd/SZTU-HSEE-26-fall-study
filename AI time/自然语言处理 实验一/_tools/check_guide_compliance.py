    ("模板章节·六、实验总结与感悟（AI辅助说明）", ANY, ["六、实验总结与感悟（AI辅助说明）"]),
    ("模板章节·七、思考题", ANY, ["七、思考题"]),
    # ---- 评分标准「内容完整、充实性（30分）」点名的四个重点 ----
    # 原文：主要考查模板中要求的内容是否齐全，重点考查实验原理（5分）、
    #       代码及注释（5分）、结果分析（10分）和总结（10分）。
    # 「代码及注释」的"注释"部分光靠标题查不出来，单独靠 verify_code_snippets.py
    # 只能核"逐字来自源码"，核不了"带不带中文注释"——那一条在 5.1 三段代码上人工确认。
    ("评分重点·实验原理", ANY, ["二、实验原理"]),
    ("评分重点·代码及注释", ALL, ["5.1", "关键代码片段"]),
